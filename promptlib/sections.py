def build_behavior(ctx: dict) -> str:
    """把行为层各段拼成一段文本（覆盖文件优先，可关段）。"""
    cfg = ctx.get("cfg") or {}
    pcfg = cfg.get("prompt") or {}
    disabled = pcfg.get("disable_sections") or []
    if isinstance(disabled, dict):
        disabled = [k for k, v in disabled.items() if not v]
    disabled = {str(x) for x in disabled}
    prompts_dir = ctx.get("prompts_dir") or ""
    parts = []
    for sid, fn in SECTIONS:
        if sid in disabled:
            continue
        text = _override(prompts_dir, sid) if prompts_dir else None
        if text is None:
            try:
                text = fn(ctx)
            except Exception:
                text = ""
        if text:
            parts.append(text.strip())
    return "\n\n".join(parts)
