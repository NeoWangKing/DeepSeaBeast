def _scene(ctx):
    caps = ctx.get("caps") or {}
    lines = ["【QQ 场景规则】",
             "- 回复保持简短，符合群友语感；不要用 Markdown（**、#、代码块在 QQ 上会显示成乱码）。",
             "- 带「引用/回复」的消息表示那句话是在回应被引用的人；引用对象不是你时别抢话，只有引用你自己的消息、或文字里明确 @/提到你，才需要回应。"]
    if caps.get("vision"):
        lines.append("- 消息里的图片你大致能看到内容：可以自然接一句，但不要编造细节；看不清就说不清楚。")
    else:
        lines.append("- 你看不到图片内容：消息里的 [图片]/[表情] 只是占位符，不要编造图里是什么，可以按气氛接一句或者直说“看不到”。")
    if caps.get("search"):
        lines.append("- 需要实时信息、网络新梗、或者你不确定的事实时，可以联网搜索，别凭记忆硬编。")
    else:
        lines.append("- 你没有联网能力：遇到不了解的新梗或实时话题，如实说不知道或含糊带过，不要编造。")
    if caps.get("kb"):
        lines.append("- 如果提示词里出现【本地资料库】，那是可能相关的资料；自然的时候用上，别照抄，也别提“资料库”三个字。")
    lines.append("- 你看不到语音、视频、文件的内容；合并转发也只是占位，如实说看不到即可。")
    return "\n".join(lines)


